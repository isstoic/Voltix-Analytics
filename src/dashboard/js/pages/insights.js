/* Business Insights & Recommendations */
(function () {
  const { Fmt, UI, M, Targets } = window;

  window.Pages.insights = {
    title: "Business Insights & Recommendations",
    sub: "Findings generated by a transparent rule engine from the metrics for the current filters. Each insight shows the rule that triggered it; if no rule fires, nothing is shown.",
    render(ctx) {
      const ins = ctx.insights(), an = ctx.anomalies();
      const list = ins.length
        ? ins.map((i) => `<article class="ins ${i.sev}"><div class="ob">${i.obs}</div><dl><dt>Supporting metric</dt><dd>${i.metric}</dd><dt>Implication</dt><dd>${i.impl}</dd><dt>Recommended action</dt><dd>${i.action}</dd><dt>KPI to monitor</dt><dd>${i.kpi}</dd></dl><div class="rule">Rule: ${i.rule}</div></article>`).join("")
        : UI.note("No insight rule was triggered for this selection. Try a longer date range.");
      return `<div class="grid">
        <section class="card c8"><div class="card-h"><div><h3>Findings (${ins.length})</h3><p class="q">Recomputed whenever the date range or a filter changes.</p></div></div>${list}</section>
        <div class="c4" style="display:grid;gap:14px;align-content:start">
          ${UI.card("", "Planning-target summary", "Illustrative targets; see Data &amp; methodology.", `<div id="in-tv"></div>`)}
          ${UI.card("", "How to read these", "", `<div class="defs"><p style="margin-top:0"><b style="color:var(--ink)">Modelled fields.</b> Margin, discount, return, channel, marketing and inventory insights rely on modelled cost, discount, return and attribution fields (see Data &amp; methodology).</p><p><b style="color:var(--ink)">Causality.</b> Attribution and co-movement are descriptive. Incrementality requires experiments.</p><p style="margin-bottom:0"><b style="color:var(--ink)">Not tracked.</b> Impressions, clicks, conversion funnels and stock history are not in the dataset.</p></div>`)}
        </div>
      </div>
      <div class="grid">${UI.card("c12", "Unusual periods in net sales", "Periods whose net sales deviate strongly from the typical level (modified z-score above 3.5 using median and MAD). Needs at least 8 full periods.", `<div id="in-an"></div>`)}</div>`;
    },
    after(ctx) {
      const t = ctx.target(), host = document.getElementById("in-tv");
      host.innerHTML = t.available
        ? `<table><tbody>${["net", "gp", "orders"].map((k) => { const m = t.metrics[k]; return `<tr><td class="l">${m.label}</td><td>${Fmt.pct(m.ach, 0)}</td><td><span class="st ${m.status}">${{ above: "Above", on: "On target", below: "Below", na: "n/a" }[m.status]}</span></td></tr>`; }).join("")}</tbody></table>`
        : UI.note(t.reason);
      const an = ctx.anomalies();
      if (!an.length) { document.getElementById("in-an").innerHTML = UI.note("No unusual periods were detected in this selection."); return; }
      UI.table("in-an", { id: "anom", rows: an, sortKey: "absz", pageSize: 8, search: false, exportName: "unusual_periods", cols: [
        { k: "label", label: "Period" }, { k: "value", label: "Net sales", fmt: (v) => Fmt.brlFull(v), raw: (v) => Math.round(v) }, { k: "expected", label: "Typical", fmt: (v) => Fmt.brlFull(v), raw: (v) => Math.round(v) },
        { k: "dev", label: "Deviation", fmt: (v) => Fmt.spct(v), cls: (r) => (r.dir === "high" ? "cell-pos" : "cell-neg") }, { k: "absz", label: "|Robust z|", fmt: (v) => v.toFixed(1) }] });
    },
  };
})();
